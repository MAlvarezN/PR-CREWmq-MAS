"""Minimal IPR (Iterative Prompt Refinement) skeleton, Sami et al. 2025, Sec. 3:

    test -> failure analysis (issue / root cause / action) -> refine system
    prompt -> re-test, until max iterations or all examples pass.

Month 1 scope: feedback is generated by the coordinator LLM and appended to
the specialist's system prompt as a corrective guideline; prompts are NOT
persisted back to registry/agents.json yet (that is month-2 work).

Usage:
    python -m scripts.ipr_loop
    MAS_MOCK=1 python -m scripts.ipr_loop
"""

import json
from datetime import datetime, timezone
from pathlib import Path

from src.agents.coordinator import CoordinatorAgent
from src.agents.specialist import DataSpecialistAgent
from src.llm import get_llm
from src.registry import AgentRegistry
from src.tools.data_tool import TOOLS

EXAMPLES = [
    {"query": "Which sol had the hottest maximum temperature?",
     "expected_substring": "404"},  # max_temp_c -16.8 occurs at sol 404
    {"query": "Which sol had the lowest pressure?",
     "expected_substring": "405"},
]

LOG = Path(__file__).resolve().parent.parent / "logs" / "ipr_log.jsonl"
FEEDBACK_PROMPT = (
    "A specialist agent failed a test.\nQuery: {query}\nSpecialist answer: {answer}\n"
    "Expected the answer to mention: {expected}\n"
    "Write a corrective guideline (1-2 sentences) to add to the specialist's "
    "system prompt. Format: GUIDELINE: <text>"
)


def run_once(llm, specialist, example):
    call, _ = CoordinatorAgent(llm, AgentRegistry().get("coordinator")).plan_tool_call(example["query"])
    answer, _ = specialist.answer(example["query"], call)
    return answer, example["expected_substring"].lower() in answer.lower()


def main(max_iterations=2):
    llm = get_llm()
    registry = AgentRegistry()
    entry = registry.get("data_specialist")
    log = {"ts": datetime.now(timezone.utc).isoformat(), "iterations": []}

    for it in range(1, max_iterations + 1):
        specialist = DataSpecialistAgent(llm, entry, TOOLS)
        results, failures = [], []
        for ex in EXAMPLES:
            answer, passed = run_once(llm, specialist, ex)
            results.append({"query": ex["query"], "passed": passed})
            if not passed:
                fb = llm.chat("You analyze agent failures.", FEEDBACK_PROMPT.format(
                    query=ex["query"], answer=answer, expected=ex["expected_substring"]))
                guideline = fb.content.replace("GUIDELINE:", "").strip()
                failures.append({"query": ex["query"], "guideline": guideline})
                entry["system_prompt"] += "\n" + guideline  # in-memory refinement

        log["iterations"].append({"iteration": it, "results": results, "failures": failures})
        passed = sum(r["passed"] for r in results)
        print(f"IPR iter {it}: {passed}/{len(EXAMPLES)} passed")
        if passed == len(EXAMPLES):
            break

    with LOG.open("a") as f:
        f.write(json.dumps(log) + "\n")
    return log


if __name__ == "__main__":
    main()
